import type { CurrencyCode, PaymentMethod, PaymentStatus, Transaction } from '@/types'
import {
  RESPONSE_CODES,
  cardMethod,
  installmentMethod,
  promptPayMethod,
  walletMethod,
} from '@/lib/payment'
import { customerById } from './customers'

interface TransactionSeed {
  id: string
  orderId: string
  paymentId: string
  customerId: string
  description: string
  amount: number
  currency?: CurrencyCode
  method: PaymentMethod
  status: PaymentStatus
  refundedAmount?: number
  authorizationCode?: string
  createdAt: string
  /** Defaults to createdAt + a few seconds when omitted. */
  updatedAt?: string
}

function responseFor(status: PaymentStatus) {
  switch (status) {
    case 'SUCCESS':
    case 'REFUNDED':
    case 'PARTIALLY_REFUNDED':
      return RESPONSE_CODES.approved
    case 'FAILED':
      return RESPONSE_CODES.declinedByIssuer
    case 'CANCELLED':
      return RESPONSE_CODES.cancelled
    default:
      return RESPONSE_CODES.pending
  }
}

function build(seed: TransactionSeed): Transaction {
  const customer = customerById.get(seed.customerId)
  if (!customer) throw new Error(`Unknown customer ${seed.customerId}`)
  const response = responseFor(seed.status)
  const settled = ['SUCCESS', 'REFUNDED', 'PARTIALLY_REFUNDED'].includes(seed.status)

  return {
    id: seed.id,
    orderId: seed.orderId,
    paymentId: seed.paymentId,
    customerId: customer.id,
    customerName: customer.name,
    customerEmail: customer.email,
    customerPhone: customer.phone,
    description: seed.description,
    amount: seed.amount,
    refundedAmount: seed.refundedAmount ?? 0,
    currency: seed.currency ?? 'THB',
    paymentMethod: seed.method,
    status: seed.status,
    authorizationCode: settled ? (seed.authorizationCode ?? '482910') : undefined,
    responseCode: response.code,
    responseMessage: response.message,
    createdAt: seed.createdAt,
    updatedAt: seed.updatedAt ?? seed.createdAt,
  }
}

